# 위 규칙으로도 안 잡히던 나머지 라벨(전체 925종 대조 결과 최종적으로 남은 것들)에 대한
# 명시적 수동 지정 — 새 라벨이 추가돼도 안전하도록 규칙 우선, 이 표는 보완용입니다.
OVERRIDES = {
    "공원 이용객 관리": ["탐방로·탐방객 관리"],
}

# 규칙에도 전혀 안 걸리는 완전히 새로운 라벨이 나중에 생기면(예: 향후 프롬프트가 다시
# 자유 텍스트로 샐 경우 대비) 최소한 하나의 카테고리는 배정되도록 하는 최종 안전장치
DEFAULT_FALLBACK = "공원계획·구역관리"


def classify(label: str) -> list[str]:
    if label in OVERRIDES:
        return OVERRIDES[label]
    low = label.lower()
    hits = []
    for cat, kws in RULES:
        for kw in kws:
            if kw.lower() in low:
                hits.append(cat)
                break
    seen = []
    for h in hits:
        if h not in seen:
            seen.append(h)
    if not seen:
        seen = [DEFAULT_FALLBACK]
    return seen[:3]


def run():
    with open(RAW_FILE, encoding="utf-8") as f:
        papers = json.load(f)

    changed = 0
    label_cache: dict[str, list[str]] = {}

    for p in papers:
        ai = p.get("ai_analysis")
        if not ai:
            continue
        old_areas = ai.get("related_work_areas") or []
        if not old_areas:
            continue

        new_areas: list[str] = []
        for label in old_areas:
            if label not in label_cache:
                label_cache[label] = classify(label)
            for cat in label_cache[label]:
                if cat not in new_areas:
                    new_areas.append(cat)

        if new_areas != old_areas:
            ai["related_work_areas_legacy"] = old_areas   # 원본 보존(참고용)
            ai["related_work_areas"] = new_areas
            changed += 1

    with open(RAW_FILE, "w", encoding="utf-8") as f:
        json.dump(papers, f, ensure_ascii=False, indent=2)

    print(f"[Reclassify] 총 {len(papers)}건 중 {changed}건의 related_work_areas를 "
          f"12개 고정 카테고리로 재분류했습니다.")
    print(f"[Reclassify] 매핑에 사용된 원본 라벨 종류: {len(label_cache)}개")
    print("[Reclassify] 다음으로 'python3 indexer.py'를 실행해서 papers.json을 갱신하세요.")


if __name__ == "__main__":
    run()
